/*
    Exercício 5
        Escreva um programa que mostre
        na tela os numeros 0 a 100,
        um por linha.
        Use o comando for.

*/

public class mostrarNumeros {
    public static void main(String[] args) {
        int i;

        for ( i = 0; i <= 100 ; i++) {
            System.out.println( i );
        }
    }
}
